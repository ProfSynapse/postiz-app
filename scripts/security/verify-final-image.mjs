import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { existsSync } from 'node:fs';
import sharp from 'sharp';
const require = createRequire(import.meta.url);
assert.equal(process.version, 'v22.23.4');
assert.equal(require('detect-libc').familySync(), 'musl');
assert.equal(require('next/package.json').version, '15.5.28');
assert.equal(sharp.versions.sharp, '0.35.5');
assert.ok(!existsSync('/app/.env'));
assert.ok(existsSync('/app/apps/frontend/src/app/(app)/api/uploads/[[...path]]/route.ts'));
const bytes = await sharp({ create: { width: 4, height: 3, channels: 4, background: '#224466' } }).avif().toBuffer();
assert.equal((await sharp(bytes).metadata()).format, 'avif');
const bcrypt = require('bcrypt');
const legacy = '$2a$10$XOPbrlUPQdwdJUpSrIF6X.LbE14qsMmKGhM1A8W9iqaG3vv1BD7WC';
assert.ok(bcrypt.compareSync('envy1362987212538', legacy));
assert.ok(bcrypt.compareSync('fixture', bcrypt.hashSync('fixture', 4)));
const { PrivateCpuProfilerBindings, CpuProfilerBindings } = require('@sentry/node-cpu-profiler');
assert.ok(PrivateCpuProfilerBindings);
CpuProfilerBindings.startProfiling('postiz-musl-fixture');
await new Promise(r => setTimeout(r, 30));
assert.ok(CpuProfilerBindings.stopProfiling('postiz-musl-fixture', 0));
const nativeModules = Object.keys(require.cache).filter(p => p.endsWith('.node'));
assert.ok(nativeModules.some(p => p.includes('musl') && p.includes('sentry_cpu_profiler')));
assert.ok(nativeModules.some(p => p.includes('bcrypt')));
console.log(JSON.stringify({ node: process.version, libc: 'musl', next: require('next/package.json').version, sharp: sharp.versions, bcrypt: require('bcrypt/package.json').version, sentry: require('@sentry/profiling-node/package.json').version, nativeModules, avif: 'encoded/decoded', bcryptHashes: 'legacy and fresh compared', sentryNative: 'profile started/stopped' }, null, 2));
